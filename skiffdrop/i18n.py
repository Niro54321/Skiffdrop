LANG = "en"


def system_language() -> str:
    name = QLocale.system().name().lower()  # e.g. "ar_ma", "zh_cn", "pt_br"
    code = name.split("_")[0]
    return code if code in S else "en"


def set_language(choice: str) -> str:
    """choice: a language code, or "" for the Windows display language."""
    global LANG
    LANG = choice if choice in S else system_language()
    return LANG


def tr(key: str, **kw) -> str:
    text = S.get(LANG, S["en"]).get(key) or S["en"].get(key, key)
    for k, v in kw.items():
        text = text.replace("{" + k + "}", str(v))
    return text
